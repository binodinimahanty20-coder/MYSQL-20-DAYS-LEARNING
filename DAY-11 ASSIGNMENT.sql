SELECT*FROM EMPLOYEE_ATTENDANCE;

SELECT EMP_NAME,DATE(LOGIN_TIME)AS LOGIN_DATE FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,TIME(LOGIN_TIME)AS LOGIN_TIME FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,YEAR(JOINING_DATE)AS JOINING_YEAR FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,MONTH(BIRTH_DATE)AS BIRTH_MONTH FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DAY(BIRTH_DATE)AS BIRTH_DAY FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,WEEK(JOINING_DATE)AS WEEK_NUMBER FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,WEEKDAY(JOINING_DATE)AS WEEKDAY_NUMBER FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATE_ADD(JOINING_DATE,INTERVAL 30 DAY)AS NEW_DATE FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATE_SUB(JOINING_DATE,INTERVAL 15 DAY)AS EARLY_DATE FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATEDIFF(CURDATE(),JOINING_DATE)AS DAYS_WORKED FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATEDIFF(LOGOUT_TIME,LOGIN_TIME)AS DAYS_DIFF FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,UNIX_TIMESTAMP(LOGIN_TIME)AS UNIX_TIME FROM EMPLOYEE_ATTENDANCE;
SELECT FROM_UNIXTIME(1700000000)AS DATETIME_VALUE;
SELECT EMP_NAME,LAST_DAY(JOINING_DATE)AS LAST_DAY_MONTH FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,MONTHNAME(BIRTH_DATE)AS MONTH_NAME,DAYNAME(BIRTH_DATE)AS DAY_NAME FROM EMPLOYEE_ATTENDANCE;

SELECT*FROM EMPLOYEE_ATTENDANCE WHERE YEAR(JOINING_DATE)=YEAR(CURDATE());
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE MONTH(BIRTH_DATE)=11;
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE MONTH(JOINING_DATE)=6;
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE DAY(BIRTH_DATE)=10;
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE QUARTER(JOINING_DATE)=2;
SELECT EMP_NAME,TIMESTAMPDIFF(YEAR,BIRTH_DATE,CURDATE())AS AGE FROM EMPLOYEE_ATTENDANCE;
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE TIMESTAMPDIFF(YEAR,JOINING_DATE,CURDATE())>3;
SELECT EMP_NAME,TIMESTAMPDIFF(HOUR,LOGIN_TIME,LOGOUT_TIME)AS WORKING_HOURS FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,TIMESTAMPDIFF(MINUTE,LOGIN_TIME,LOGOUT_TIME)AS WORKING_MINUTES FROM EMPLOYEE_ATTENDANCE;
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE TIME(LOGIN_TIME)<'09:00:00';
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE TIME(LOGIN_TIME)>'09:10:00';
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE DAYNAME(JOINING_DATE)='Monday';
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE MONTHNAME(BIRTH_DATE)LIKE'J%';
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE WEEK(JOINING_DATE)=25;
SELECT EMP_NAME,LAST_DAY(BIRTH_DATE)AS LAST_DAY_BIRTH FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATE_ADD(JOINING_DATE,INTERVAL 1 YEAR)AS NEXT_YEAR FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATE_SUB(JOINING_DATE,INTERVAL 2 MONTH)AS PREV_DATE FROM EMPLOYEE_ATTENDANCE;
SELECT*FROM EMPLOYEE_ATTENDANCE WHERE YEAR(BIRTH_DATE)=YEAR(CURDATE());
SELECT EMP_NAME,DATE_FORMAT(JOINING_DATE,'%d-%m-%Y')AS FORMATTED_DATE FROM EMPLOYEE_ATTENDANCE;
SELECT EMP_NAME,DATE_FORMAT(LOGIN_TIME,'%d-%M-%Y')AS FORMATTED_LOGIN FROM EMPLOYEE_ATTENDANCE;