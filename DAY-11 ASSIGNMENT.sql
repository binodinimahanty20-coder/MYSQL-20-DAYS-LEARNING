DROP TABLE employee_attendance;
CREATE TABLE employee_attendance
(
	emp_id INT PRIMARY KEY AUTO_INCREMENT,
	emp_name VARCHAR(100),
	department VARCHAR(50),
	joining_date DATE,
	birth_date DATE,
	login_time DATETIME,
	logout_time DATETIME,
	salary DECIMAL(10,2)
);

